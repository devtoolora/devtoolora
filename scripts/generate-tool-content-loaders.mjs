import { existsSync, readdirSync, realpathSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const catalogDir = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'packages',
  'tools',
  'src',
  'catalog',
);
const outFile = join(catalogDir, 'content.generated.ts');

function subfolders(dir) {
  return readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name);
}

export function renderToolContentLoaders() {
  const entries = [];

  for (const domain of subfolders(catalogDir)) {
    for (const id of subfolders(join(catalogDir, domain))) {
      if (existsSync(join(catalogDir, domain, id, 'content.ts'))) entries.push({ domain, id });
    }
  }

  const lines = entries
    .sort((a, b) => (a.id < b.id ? -1 : 1))
    .map(({ domain, id }) => `  '${id}': () => import('./${domain}/${id}/content'),`);

  return `// Generated by scripts/generate-tool-content-loaders.mjs. Do not edit.
import type { ToolContent } from '@devtoolora/core';

export const toolContentLoaders: Record<string, () => Promise<{ content: ToolContent }>> = {
${lines.join('\n')}
};
`;
}

// Compare real paths so a symlinked checkout still runs the generator.
if (
  process.argv[1] &&
  realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))
) {
  writeFileSync(outFile, renderToolContentLoaders());
}
