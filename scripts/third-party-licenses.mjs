#!/usr/bin/env node
// Run `npm run licenses` after changing npm or Cargo dependencies.
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const licenseFile = /^(licen[cs]e|copying|notice)/i;

function licenseTexts(directory) {
  if (!existsSync(directory)) return [];

  return readdirSync(directory)
    .filter((name) => licenseFile.test(name))
    .sort()
    .map((name) => readFileSync(join(directory, name), 'utf8').trim())
    .filter(Boolean);
}

function npmPackages() {
  const lock = JSON.parse(readFileSync(join(root, 'package-lock.json'), 'utf8'));

  return Object.entries(lock.packages)
    .filter(([path, entry]) => path.includes('node_modules/') && !entry.link)
    .filter(([, entry]) => !entry.dev && !entry.devOptional)
    .map(([path, entry]) => ({
      license: entry.license ?? 'UNKNOWN',
      name: path.slice(path.lastIndexOf('node_modules/') + 'node_modules/'.length),
      texts: licenseTexts(join(root, path)),
      version: entry.version,
    }));
}

function rustCrates() {
  const tauriRoot = join(root, 'apps/desktop/src-tauri');

  // The desktop app lives on its own branch until it ships; without it there are no crates.
  if (!existsSync(tauriRoot)) return [];

  const metadata = JSON.parse(
    execFileSync('cargo', ['metadata', '--format-version', '1', '--locked'], {
      cwd: tauriRoot,
      encoding: 'utf8',
      maxBuffer: 64 * 1024 * 1024,
    }),
  );
  const workspace = new Set(metadata.workspace_members);

  return metadata.packages
    .filter((crate) => !workspace.has(crate.id))
    .map((crate) => ({
      license: crate.license ?? 'UNKNOWN',
      name: crate.name,
      texts: licenseTexts(dirname(crate.manifest_path)),
      version: crate.version,
    }));
}

function uniqueByNameVersion(packages) {
  const seen = new Map();

  for (const entry of packages) seen.set(`${entry.name}@${entry.version}`, entry);

  return [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
}

function table(packages) {
  return [
    '| Package | Version | License |',
    '| --- | --- | --- |',
    ...packages.map(({ license, name, version }) => `| ${name} | ${version} | ${license} |`),
  ].join('\n');
}

function textSections(packages) {
  const byText = new Map();

  for (const entry of packages) {
    for (const text of entry.texts) {
      const owners = byText.get(text) ?? [];

      owners.push(`${entry.name}@${entry.version}`);
      byText.set(text, owners);
    }
  }

  return [...byText.entries()]
    .map(([text, owners]) => `### ${owners.join(', ')}\n\n\`\`\`text\n${text}\n\`\`\``)
    .join('\n\n');
}

const npm = uniqueByNameVersion(npmPackages());
const rust = uniqueByNameVersion(rustCrates());
const missing = [...npm, ...rust].filter((entry) => !entry.texts.length).map((entry) => entry.name);

writeFileSync(
  join(root, 'THIRD_PARTY_LICENSES.md'),
  `# Third-party licenses

Dev Toolora ships the open source packages listed below. This file is generated by
\`npm run licenses\`; do not edit it by hand.

## npm packages (web, VS Code extension and desktop app)

${table(npm)}

## Rust crates (desktop app)

${table(rust)}

## License texts

Packages without a license file in their distribution are covered by the license named in the
tables above.

${textSections([...npm, ...rust])}
`,
);

console.log(
  `THIRD_PARTY_LICENSES.md: ${npm.length} npm packages, ${rust.length} crates, ${missing.length} without a license file.`,
);
