const { writeFileSync } = require('node:fs');
const { join } = require('node:path');
const { requireTs } = require('./lib/requireTs.cjs');

const tools = requireTs(join(__dirname, '..', 'packages', 'tools', 'src', 'index.ts'));

const domainArrays = tools.domainTools;

const toolDomains = {};

for (const [domain, definitions] of Object.entries(domainArrays)) {
  for (const tool of definitions) {
    if (toolDomains[tool.id]) {
      throw new Error(`Tool ${tool.id} appears in two domains: ${toolDomains[tool.id]}, ${domain}`);
    }

    toolDomains[tool.id] = domain;
  }
}

const entries = Object.keys(toolDomains)
  .sort()
  .map((id) => `  '${id}': '${toolDomains[id]}',`)
  .join('\n');
const source = `// Generated by scripts/generate-browser-catalog-domains.js. Do not edit.
export const toolDomains = {
${entries}
} as const;
`;

writeFileSync(
  join(__dirname, '..', 'packages', 'browser-catalog', 'src', 'toolDomains.generated.ts'),
  source,
);
