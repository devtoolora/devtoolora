import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { build } from 'esbuild';

const require = createRequire(import.meta.url);
const Ajv = require('ajv').default;
const Ajv2019 = require('ajv/dist/2019').default;
const Ajv2020 = require('ajv/dist/2020').default;
const addFormats = require('ajv-formats');
const standaloneCode = require('ajv/dist/standalone').default;
const drafts = [
  { engine: Ajv, name: 'validateMeta7', uri: 'http://json-schema.org/draft-07/schema#' },
  {
    engine: Ajv2019,
    name: 'validateMeta2019',
    uri: 'https://json-schema.org/draft/2019-09/schema',
  },
  {
    engine: Ajv2020,
    name: 'validateMeta2020',
    uri: 'https://json-schema.org/draft/2020-12/schema',
  },
];
const output = [
  '// Generated from the bundled official meta-schemas by generate-json-schema-meta.mjs. Do not edit.',
  '// Static validation functions intentionally avoid eval/new Function at runtime.',
  'import equalModule from "ajv/dist/runtime/equal.js";',
  'const equalRuntime = { default: typeof equalModule === "function" ? equalModule : equalModule.default };',
];

for (const draft of drafts) {
  const ajv = new draft.engine({ allErrors: false, code: { source: true }, strict: false });

  addFormats(ajv);
  const validator = ajv.getSchema(draft.uri);

  if (!validator) throw new Error(`Missing bundled meta-schema: ${draft.uri}.`);

  const code = standaloneCode(ajv, validator).replaceAll(
    'require("ajv/dist/runtime/equal")',
    'equalRuntime',
  );

  if (/\brequire\(/.test(code))
    throw new Error('Standalone meta-schema contains an unbundled runtime dependency.');

  output.push(
    `/** @type {import('ajv').ValidateFunction} */\nexport const ${draft.name} = (() => { const module = { exports: {} }; ${code} return module.exports; })();`,
  );
}

writeFileSync(
  new URL('../src/schema/metaValidators.generated.js', import.meta.url),
  output.join('\n') + '\n',
);

writeFileSync(
  new URL('../src/schema/metaValidators.generated.d.ts', import.meta.url),
  `// Generated by generate-json-schema-meta.mjs. Do not edit.\nimport type { ValidateFunction } from 'ajv';\n${drafts.map((draft) => `export declare const ${draft.name}: ValidateFunction;`).join('\n')}\n`,
);

// Upstream ambient-location detection cannot handle VS Code blob workers.
// This inert base resolves relative IDs without accessing the network.
const engineRoot = dirname(require.resolve('@cfworker/json-schema/package.json'));
const engine = await build({
  bundle: true,
  format: 'esm',
  minify: false,
  platform: 'neutral',
  plugins: [
    {
      name: 'local-schema-base-uri',
      setup(builder) {
        builder.onLoad({ filter: /[\\/]dereference\.js$/ }, ({ path }) => {
          const source = readFileSync(path, 'utf8');
          const initializer =
            /export let initialBaseURI = typeof self[\s\S]*?: new URL\('https:\/\/github\.com\/cfworker'\);/;

          if (!initializer.test(source))
            throw new Error('Schema engine initializer changed; review blob-worker compatibility.');

          return {
            contents: source.replace(
              initializer,
              'export let initialBaseURI = new URL("https://local.invalid/schema");',
            ),
            loader: 'js',
          };
        });
      },
    },
  ],
  stdin: {
    contents: `export { dereference, format, validate } from ${JSON.stringify(join(engineRoot, 'dist/esm/index.js'))};`,
    loader: 'js',
    resolveDir: engineRoot,
  },
  write: false,
});
