import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const packagePath = require.resolve('@fontsource/noto-sans/package.json');
const packageUrl = new URL(`file://${packagePath}`);
const license = await readFile(new URL('LICENSE', packageUrl), 'utf8');
const entries = [];

for (const weight of [400, 700]) {
  for (const subset of ['latin', 'latin-ext']) {
    const bytes = await readFile(
      new URL(`files/noto-sans-${subset}-${weight}-normal.woff`, packageUrl),
    );

    entries.push(
      `  { base64: '${bytes.toString('base64')}', bold: ${weight === 700}, subset: '${subset}' },`,
    );
  }
}

const source = [
  '// Generated by scripts/generate-pdf-fonts.mjs. Offline font bytes; do not edit manually.',
  '// Noto Sans, Copyright 2022 The Noto Project Authors. SIL OFL-1.1.',
  `export const pdfFontLicense: string = ${JSON.stringify(license)};`,
  'export const pdfFontData: Array<{ base64: string; bold: boolean; subset: string }> = [',
  ...entries,
  '];',
  '',
].join('\n');

await writeFile(new URL('../src/pdf/fonts.generated.ts', import.meta.url), source);
