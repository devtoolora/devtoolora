import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const data = '4.0.0_best_int';
const runtimes = {
  heic: [
    { kind: 'script', name: 'libheif.js', source: 'libheif-js/libheif-wasm/libheif.js' },
    { kind: 'data', name: 'libheif.wasm', source: 'libheif-js/libheif-wasm/libheif.wasm' },
  ],
  ocr: [
    {
      kind: 'script',
      name: 'tesseract-core-simd-lstm.js',
      source: 'tesseract.js-core/tesseract-core-simd-lstm.js',
    },
    {
      kind: 'data',
      name: 'tesseract-core-simd-lstm.wasm',
      source: 'tesseract.js-core/tesseract-core-simd-lstm.wasm',
    },
    {
      kind: 'data',
      language: 'eng',
      name: 'eng.traineddata.gzip',
      source: `@tesseract.js-data/eng/${data}/eng.traineddata.gz`,
    },
    {
      kind: 'data',
      language: 'ces',
      name: 'ces.traineddata.gzip',
      source: `@tesseract.js-data/ces/${data}/ces.traineddata.gz`,
    },
  ],
};

const manifest = {};

for (const [runtime, files] of Object.entries(runtimes)) {
  manifest[runtime] = [];

  for (const { kind, language, name, source } of files) {
    const bytes = await readFile(require.resolve(source));

    manifest[runtime].push({
      bytes: bytes.length,
      kind,
      ...(language ? { language } : {}),
      name,
      sha256: createHash('sha256').update(bytes).digest('hex'),
      source,
    });
  }
}

const output = [
  '// Generated by scripts/generate-runtime-manifest.mjs; do not edit manually.',
  "import type { RuntimeFileEntry, RuntimeName } from './files';",
  '',
  `export const runtimeManifest: Record<RuntimeName, RuntimeFileEntry[]> = ${JSON.stringify(manifest, null, 2)};`,
  '',
].join('\n');

await writeFile(new URL('../src/runtime/manifest.generated.ts', import.meta.url), output);
