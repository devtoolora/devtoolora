import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const registeredPorts = new Set([
  1080, 1194, 1433, 1434, 1521, 1701, 1723, 1812, 1813, 1883, 1900, 2049, 2181, 2375, 2376, 2379,
  2380, 3000, 3268, 3269, 3306, 3389, 3478, 3690, 4369, 5000, 5060, 5061, 5222, 5269, 5353, 5355,
  5432, 5601, 5671, 5672, 5683, 5900, 5984, 5985, 5986, 6379, 6443, 6514, 7001, 8000, 8008, 8080,
  8081, 8086, 8088, 8443, 8883, 8888, 9000, 9090, 9092, 9093, 9100, 9200, 9300, 9418, 11211, 27017,
]);
const protocolOrder = ['tcp', 'udp', 'sctp', 'dccp'];
const csvPath = process.argv[2];

if (!csvPath) throw new Error('Usage: node generate-port-registry.mjs <registry.csv>');

function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;

  for (let index = 0; index < text.length; index += 1) {
    const char = text[index];

    if (quoted) {
      if (char !== '"') field += char;
      else if (text[index + 1] === '"') {
        field += '"';
        index += 1;
      } else quoted = false;
    } else if (char === '"') quoted = true;
    else if (char === ',') {
      row.push(field);
      field = '';
    } else if (char === '\n' || char === '\r') {
      if (char === '\r' && text[index + 1] === '\n') index += 1;

      row.push(field);
      rows.push(row);
      row = [];
      field = '';
    } else field += char;
  }

  if (field || row.length > 0) rows.push([...row, field]);

  return rows;
}

const collapse = (value) => value.replace(/\s+/g, ' ').trim();
const [, ...records] = parseCsv(readFileSync(csvPath, 'utf8'));
const merged = new Map();
let newest = '';

for (const record of records) {
  const [service, portText, protocol, description] = record.map(collapse);

  if (record[7] > newest) newest = record[7];

  if (!service || !/^\d+$/.test(portText) || !protocolOrder.includes(protocol)) continue;

  const port = Number(portText);

  if (port > 1023 && !registeredPorts.has(port)) continue;

  if (/^(reserved|unassigned)\b/i.test(description)) continue;

  const key = `${port}\t${service}`;
  const entry = merged.get(key) ?? { description, port, protocols: new Set(), service };

  entry.protocols.add(protocol);
  merged.set(key, entry);
}

const lines = [...merged.values()]
  .sort((a, b) => a.port - b.port || a.service.localeCompare(b.service, 'en'))
  .map((entry) => {
    const protocols = protocolOrder.filter((name) => entry.protocols.has(name)).join(',');

    return `${entry.port}\t${entry.service}\t${protocols}\t${entry.description}\n`;
  });
const output = `// Generated by scripts/generate-port-registry.mjs from the IANA Service Name and Transport
// Protocol Port Number Registry CSV (modification dates up to ${newest}). Do not edit.
export const ianaPortRows: string = ${JSON.stringify(lines.join(''))};
`;
const target = join(dirname(fileURLToPath(import.meta.url)), '../src/network/portRegistryData.ts');

writeFileSync(target, output);
console.log(`${lines.length} rows, ${output.length} characters`);
