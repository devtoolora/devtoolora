function buildHttpRequest(fields: Record<string, string>): ToolResult {
  return renderRequest(
    withToolError(() =>
      webFunctions.buildHttpRequest({
        url: fields.url ?? '',
        method: fields.method,
        query: fields.query,
        headers: fields.headers,
        bodyMode: fields.bodyMode,
        body: fields.body,
        rawContentType: fields.rawContentType,
        authMode: fields.authMode,
        bearerToken: fields.bearerToken,
        apiKeyName: fields.apiKeyName,
        apiKeyValue: fields.apiKeyValue,
        apiKeyLocation: fields.apiKeyLocation,
        basicUsername: fields.basicUsername,
        basicPassword: fields.basicPassword,
      }),
    ),
    fields.export,
    (fields.authMode ?? 'none') !== 'none',
  );
}
